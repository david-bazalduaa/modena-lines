let errors = 0;
for (const line of newPircLines) {
  const g = new Chess();
  const tokens = line.pgn.split(/\s+/).filter(t => !/^\d+\.$/.test(t));
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (!g.move(t, { sloppy: true })) {
      console.error(`FAIL: ${line.id} at ply ${i} token '${t}'`);
      errors++;
      break;
    }
  }
  if (g.turn() !== 'w') {
    console.error(`FAIL: ${line.id} does not end on Black's move (turn=${g.turn()})`);
    errors++;
  }
  console.log(`PASS: ${line.id} (${g.history().length} plies) FEN: ${g.fen()}`);
}

if (errors === 0) {
  console.log(`ALL ${newPircLines.length} NEW PIRC DEFENSE LINES VALID!`);
} else {
  console.error(`${errors} ERRORS FOUND.`);
}
